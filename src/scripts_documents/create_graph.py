import numpy as np
import matplotlib.pyplot as plt

def create_graph(x: list[int], y: list[list[int]], labels: list[str], title: str, xlabel: str, ylabel: str, path: str,
                 stdev_values: list[list[float]] = None, legend_loc: str = 'lower center', fontsize_title=20,
                 fontsize_labels=18, fontsize_legend=16, fontsize_sticks=12):
    plt.figure(figsize=(8, 6), dpi=150)
    for i, (series, label) in enumerate(zip(y, labels)):
        y_value = np.array(series, dtype=float)
        line, = plt.plot(x, y_value, label=label, linewidth=1.8, zorder=3)
        if stdev_values is not None:
            stdev = np.array(stdev_values[i], dtype=float)
            sample_sizes = np.array(x, dtype=float)
            ci95 = 1.96 * stdev / np.sqrt(sample_sizes)
            lower = np.maximum(y_value - ci95, 1)
            upper = y_value + ci95
            plt.fill_between(x, lower, upper, color=line.get_color(), alpha=0.2, zorder=1)
    plt.title(title, {'fontsize': fontsize_title})
    plt.xlabel(xlabel, {'fontsize': fontsize_labels})
    plt.ylabel(ylabel, {'fontsize': fontsize_labels})
    plt.xticks([i for i in range(0, 1501, 150)], fontsize=fontsize_sticks)
    plt.yticks(fontsize=fontsize_sticks)
    if legend_loc is not None:
        plt.legend(loc=legend_loc, fontsize=fontsize_legend)
    plt.tight_layout()
    plt.grid()
    plt.savefig(path, bbox_inches='tight', dpi=150)
    plt.close()

