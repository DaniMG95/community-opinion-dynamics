def create_graph(x: list[int], y: list[list[int]], labels: list[str], title: str, xlabel: str, ylabel: str, path: str,
                 stdev_values: list[list[float]] = None):
    plt.figure(figsize=(8, 6), dpi=150)
    for i, (series, label) in enumerate(zip(y, labels)):
        y_value = np.array(series, dtype=float)
        line, = plt.plot(x, y_value, label=label, linewidth=1.8, zorder=3)
        if stdev_values is not None:
            stdev = np.array(stdev_values[i], dtype=float)
            lower = np.maximum(y_value - stdev, 1)
            upper = y_value + stdev
            plt.fill_between(x, lower, upper, color=line.get_color(), alpha=0.2, zorder=1)
    plt.title(title, {'fontsize': 20})
    plt.xlabel(xlabel, {'fontsize': 18})
    plt.ylabel(ylabel, {'fontsize': 18})
    plt.xticks(x[::5], fontsize=12)
    plt.yticks(fontsize=12)
    plt.legend(loc='lower center', fontsize=16)
    plt.tight_layout()
    plt.grid()
    plt.savefig(path, bbox_inches='tight', dpi=150)
    plt.close()

