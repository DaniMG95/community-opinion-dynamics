def create_graph(x: list[int], y: list[list[int]], labels: list[str], title: str, xlabel: str, ylabel: str, path: str,
                 stdev_values: list[list[float]] = None):
    plt.figure(figsize=(8, 6), dpi=150)
    for i, values in enumerate(zip(y, labels)):
        y_value = np.array(values[0])
        label = values[1]
        plt.plot(x, y_value, label=label)
        if stdev_values is not None:
            stdev = np.array(stdev_values[i])
            plt.fill_between(x, y_value - stdev, y_value + stdev, alpha=0.2)
    plt.title(title)
    plt.xlabel(xlabel)
    plt.ylabel(ylabel)
    plt.xticks(x)
    plt.legend(loc='lower center', fontsize=8)
    plt.tight_layout()
    plt.grid()
    plt.savefig(path, bbox_inches='tight', dpi=150)
    plt.close()

